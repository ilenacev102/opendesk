"""Vendor Google Fonts as local woff2 files (run once, no runtime dependency).

Usage:
    python3 scripts/vendor_fonts.py

Downloads the variable Inter/Sora subsets into ``static/fonts/`` and rewrites
``static/css/fonts.css`` to point at ``/static/fonts/``. Network is only needed
while running this maintenance script; the app itself never talks to Google.
"""

import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "static" / "fonts"
CSS_PATH = ROOT / "static" / "css" / "fonts.css"

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Inter:wght@400..800&family=Sora:wght@600..800&display=swap"
)
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)
BLOCK = re.compile(
    r"/\*\s*(?P<subset>[a-z-]+)\s*\*/\s*@font-face\s*\{(?P<body>.*?)\}",
    re.S,
)


def _fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310
        return resp.read()


def main() -> int:
    css = _fetch(CSS_URL).decode("utf-8")
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    out = [
        "/* Self-hosted Inter + Sora (generated by scripts/vendor_fonts.py). */",
    ]
    seen = set()
    for match in BLOCK.finditer(css):
        body = match.group("body")
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        weight = re.search(r"font-weight:\s*([^;]+);", body).group(1).strip()
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)
        name = f"{family.lower()}-{match.group('subset')}.woff2"
        if name not in seen:
            (FONT_DIR / name).write_bytes(_fetch(url))
            seen.add(name)
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", body).group(1)
        out.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/static/fonts/{name}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n"
            "}"
        )
    CSS_PATH.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"vendored {len(seen)} woff2 files -> {FONT_DIR}")
    print(f"wrote {CSS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
